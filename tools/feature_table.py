#!/usr/bin/env python3
"""Task: "产品经理会把一个个feature列出来表格，工程师一个一个实现。但我们现在的issues都只是猜测的指标。"
Generates the PM feature table from measurements, not guesses: one row per Strata CUDA kernel file
(src/kernels/cuda/*.cu at Strata HEAD), every number taken from git or the source text, every row carrying
its evidence SHAs. Port status comes from tools/ref_check.py.

Columns (all measured):
  commits / first / last   git log -- <file>: how much and how recently Strata works on it
  loc, kernels             lines; count of __global__ functions
  wave64 path              file contains STRATA_HIP_GFX906 (Strata already has a wave64 layout -> port verbatim)
  warp32 ops               __shfl*_sync / __ballot_sync / __activemask uses (each needs wave64 review on ivcore10)
  tc ops                   wmma / mma.sync / ldmatrix uses (tensor-core paths; capability per probe_phase0)
  fp64                     uses of double (BI-V100 fp64 rate matters for reductions kept in double)
  port                     baloon file + ref_check status (OK / STALE / UNPINNED) or "-"
Rows are ordered: not ported first, then by "wave64 path" (cheapest port), then by recent activity.
Usage: python3 tools/feature_table.py [--strata ../Strata] [-o STRATA_FEATURE_TABLE_GEN.md]
"""
import os, re, subprocess, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ref_check  # noqa: E402

ROOT = ref_check.ROOT
WARP32 = re.compile(r"__shfl(?:_xor|_down|_up)?_sync|__ballot_sync|__activemask|__any_sync|__all_sync")
TC = re.compile(r"\bwmma::|\bmma\.sync|\bldmatrix\b|\bmma_sync\b")
FP64 = re.compile(r"\bdouble\b")
GLOBAL = re.compile(r"__global__")


def main():
    strata = sys.argv[sys.argv.index("--strata") + 1] if "--strata" in sys.argv else os.path.join(ROOT, "..", "Strata")
    out = sys.argv[sys.argv.index("-o") + 1] if "-o" in sys.argv else os.path.join(ROOT, "STRATA_FEATURE_TABLE_GEN.md")
    if ref_check.git(strata, "rev-parse", "HEAD")[0]:
        sys.exit(f"no Strata clone at {strata}")
    _, head = ref_check.git(strata, "log", "-1", "--format=%h %ad", "--date=short")
    _, total = ref_check.git(strata, "rev-list", "--count", "HEAD")
    kdir = os.path.join(strata, "src", "kernels", "cuda")

    ports = {}
    for f in sorted(os.listdir(os.path.join(ROOT, "src"))):
        if f.startswith("ix_"):
            for r in ref_check.check(strata, os.path.join(ROOT, "src", f)):
                ports.setdefault(r["strata"], []).append(f"{r['port'].split('/')[-1]} {r['status']}")

    rows = []
    for f in sorted(os.listdir(kdir)):
        if not f.endswith(".cu"):
            continue
        rel = f"src/kernels/cuda/{f}"
        txt = open(os.path.join(kdir, f), errors="replace").read()
        _, log = ref_check.git(strata, "log", "--format=%h %ad", "--date=short", "--", rel)
        log = log.split("\n")[:-1] if log else []
        rows.append(dict(
            file=f, commits=len(log), last=log[0] if log else "-", first=log[-1] if log else "-",
            loc=txt.count("\n"), kernels=len(GLOBAL.findall(txt)), wave64="STRATA_HIP_GFX906" in txt,
            warp32=len(WARP32.findall(txt)), tc=len(TC.findall(txt)), fp64=len(FP64.findall(txt)),
            port="; ".join(ports.get(rel, [])) or "-"))
    rows.sort(key=lambda r: (r["port"] != "-", not r["wave64"], -int(r["last"].split()[-1].replace("-", "") if r["last"] != "-" else 0), r["file"]))

    L = [f"# Strata kernel feature table (generated by tools/feature_table.py — do not edit by hand)", "",
         f"Strata HEAD {head.strip()}, {total.strip()} commits. Every value below is measured from git or the source "
         f"text; the SHAs are the evidence. Re-run the script to refresh.", "",
         "| # | Strata kernel file | commits | first | last | loc | `__global__` | wave64 path | warp32 ops | tc ops | fp64 | baloon port |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(rows, 1):
        L.append(f"| {i} | `{r['file']}` | {r['commits']} | {r['first']} | {r['last']} | {r['loc']} | {r['kernels']} | "
                 f"{'yes' if r['wave64'] else 'no'} | {r['warp32']} | {r['tc']} | {r['fp64']} | {r['port']} |")
    n_port = sum(r["port"] != "-" for r in rows)
    L += ["", f"{len(rows)} kernel files, {n_port} with a baloon port, "
          f"{sum(r['wave64'] and r['port'] == '-' for r in rows)} unported files already carry a wave64 (gfx906) path."]
    open(out, "w").write("\n".join(L) + "\n")
    print("\n".join(L[:12])); print(f"... wrote {out} ({len(rows)} rows)")


if __name__ == "__main__":
    main()
