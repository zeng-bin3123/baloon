// Generates ple_oracle_vectors.inc: hash cases (window -> 16 rows) and the synthetic-table probe constants.
// Run: gen_oracle > ple_oracle_vectors.inc
#include "ple_table_common.hpp"
using namespace baloon;
struct C { std::vector<int64_t> w; };
int main() {
    const std::vector<C> cs = {
        {{5}}, {{7, 11}}, {{3, 100, 2000}}, {{3, 248044, 2000}}, {{248044, 9, 77}}, {{0, 0, 0}}};
    std::printf("// generated by tests/k30_ple_table/gen_oracle.cpp - do not edit\n#include <array>\n#include <cstdint>\n");
    std::printf("struct HashCase { const int64_t* tokens; int n; const int64_t* prev; int n_prev; const uint64_t* rows; };\n");
    for (size_t i = 0; i < cs.size(); ++i) {
        const auto& w = cs[i].w;
        uint64_t rows[PLE_N_HEADS];
        ngram_rows(w.data(), (int)w.size(), PLE_EOS_TOKEN_ID, rows);
        std::printf("static constexpr std::array<int64_t, %zu> case%zu_tokens = {{", w.size(), i);
        for (size_t k = 0; k < w.size(); ++k) std::printf("%s%lldLL", k ? ", " : "", (long long)w[k]);
        std::printf("}};\nstatic constexpr std::array<int64_t, %zu> case%zu_prev = {{", w.size() == 1 ? (size_t)1 : w.size() - 1, i);
        if (w.size() == 1) std::printf("-1LL");
        for (size_t k = 0; k + 1 < w.size(); ++k) std::printf("%s%lldLL", k ? ", " : "", (long long)w[k]);
        std::printf("}};\nstatic constexpr std::array<uint64_t, 16> case%zu_rows = {{", i);
        for (int h = 0; h < PLE_N_HEADS; ++h) std::printf("%s%lluULL", h ? ", " : "", (unsigned long long)rows[h]);
        std::printf("}};\n");
    }
    std::printf("static constexpr int kHashCaseCount = %zu;\nstatic constexpr std::array<HashCase, %zu> kHashCases = {{\n", cs.size(), cs.size());
    for (size_t i = 0; i < cs.size(); ++i)
        std::printf("    {case%zu_tokens.data(), %zu, case%zu_prev.data(), %zu, case%zu_rows.data()},\n", i, cs[i].w.size(), i,
                    cs[i].w.size() == 1 ? (size_t)1 : cs[i].w.size() - 1, i);
    std::printf("}};\n");
    // synthetic table
    const uint64_t probe[] = {0, 1, 17, 255, 1000, 2047};
    uint64_t sum = 0;
    for (uint64_t r : probe) for (int j = 0; j < PLE_ROW_BYTES; ++j) sum += k30::synth_byte(r, j);
    // split-half vs interleaved nibble order, measured on block 0 of probe row 1: positions whose element index differs
    uint8_t row[PLE_ROW_BYTES];
    for (int j = 0; j < PLE_ROW_BYTES; ++j) row[j] = k30::synth_byte(1, j);
    int sep = 0;
    for (int j = 0; j < 16; ++j) {
        const int lo = row[2 + j] & 15, hi = row[2 + j] >> 4;
        // split: lo->j, hi->j+16 ; interleaved: lo->2j, hi->2j+1
        int s[32] = {0}, il[32] = {0};
        s[j] = lo; s[j + 16] = hi + 100; il[2 * j] = lo; il[2 * j + 1] = hi + 100;
        (void)s; (void)il;
        if (j != 2 * j) ++sep;
        if (j + 16 != 2 * j + 1) ++sep;
    }
    std::printf("static constexpr uint64_t kTableDataStart = %lluULL;\nstatic constexpr uint64_t kTableRows = %lluULL;\n",
                (unsigned long long)k30::kSynthStart, (unsigned long long)k30::kSynthRows);
    std::printf("static constexpr uint64_t kTableFileSize = %lluULL;\n",
                (unsigned long long)(k30::kSynthStart + k30::kSynthRows * PLE_ROW_BYTES));
    std::printf("static constexpr uint64_t kValueOffset = 0;\nstatic constexpr uint64_t kValueBytes = %d;\n", PLE_ROW_BYTES);
    std::printf("static constexpr uint64_t kKeyScalesOffset = 0;\nstatic constexpr uint64_t kKeyScalesBytes = 2;\n");
    std::printf("static constexpr uint64_t kKeyCodesOffset = 2;\nstatic constexpr uint64_t kKeyCodesBytes = 16;\n");
    std::printf("static constexpr int kProbeCount = %zu;\nstatic constexpr std::array<uint64_t, %zu> kProbeRows = {{", sizeof probe / sizeof *probe, sizeof probe / sizeof *probe);
    for (size_t i = 0; i < sizeof probe / sizeof *probe; ++i) std::printf("%s%lluULL", i ? ", " : "", (unsigned long long)probe[i]);
    std::printf("}};\nstatic constexpr uint64_t kProbeSum = %lluULL;\n", (unsigned long long)sum);
    std::printf("static constexpr int kInterleavedSeparation = %d;\n", sep);
    return 0;
}
